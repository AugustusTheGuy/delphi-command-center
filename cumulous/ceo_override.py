"""CEOOVERRIDE.md generator — local HTTPS challenge link (portable host)."""

from __future__ import annotations

from pathlib import Path

from cumulous.paths import ceo_override_md, ensure_internal


def write_ceo_override_md(port: int = 8765, host: str = "127.0.0.1") -> Path:
    """Write clickable markdown for CEO Override account edit flow.

    Prefer local HTTPS/HTTP bridge URL for portability to future control machines.
    """
    ensure_internal()
    path = ceo_override_md()
    url = f"http://{host}:{port}/ceo-override"
    deep = "cumulous://ceo-override"
    text = f"""# CEO Override (BEARACCOUNT)

**Keep this file private.** It lives under your Cumulous home (not git).

## Open CEO Override setup / edit

Click or open:

- **Bridge URL (preferred):** [{url}]({url})
- **App deep link (if registered):** [{deep}]({deep})

## What happens

1. Cumulous shows a **30-minute 4-digit code** on this computer.
2. The same code is **pushed to all Apple devices** for:
   - the user who started the request, and
   - every device linked to CEO Override / BEARACCOUNT.
3. Enter the code here to create or edit BEARACCOUNT.
4. On-screen code always works even if push fails.

## Future computer

Point this URL at the new control host's Cumulous bridge (same Tailscale MagicDNS or localhost port). Re-run Cumulous once to regenerate this file.

---
Generated by Cumulous Cloud.
"""
    path.write_text(text)
    # Also drop a desktop copy if Desktop exists
    desktop = Path.home() / "Desktop" / "CEOOVERRIDE.md"
    try:
        desktop.write_text(text)
    except OSError:
        pass
    return path
